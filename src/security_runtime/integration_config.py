"""Shared, transactional project MCP configuration editing."""
from __future__ import annotations

import json
import os
import shutil
import tempfile
from pathlib import Path
from typing import Callable
from .git import GitService


SERVER_NAME = "ai-security-runtime"


class IntegrationConfigError(ValueError):
    pass


class IntegrationConfigStore:
    def __init__(self, workspace: Path, relative_path: str):
        self.workspace = workspace.resolve()
        self.path = self.workspace / relative_path
        self.backup = self.path.with_name(self.path.name + ".security-check.bak")

    def _check_path(self) -> None:
        if self.path.is_symlink() or self.path.parent.is_symlink():
            raise IntegrationConfigError("Configuration symlinks are not supported")
        if not self.path.parent.resolve().is_relative_to(self.workspace):
            raise IntegrationConfigError("Configuration path is outside the workspace")

    def load(self) -> dict:
        self._check_path()
        if not self.path.exists():
            return {"mcpServers": {}}
        try:
            value = json.loads(self.path.read_text(encoding="utf-8-sig"))
        except (OSError, UnicodeError, json.JSONDecodeError) as exc:
            raise IntegrationConfigError("Existing configuration is invalid JSON. No changes were made.") from exc
        if not isinstance(value, dict) or not isinstance(value.get("mcpServers", {}), dict):
            raise IntegrationConfigError("Existing configuration has an invalid mcpServers object. No changes were made.")
        return value

    def entry(self) -> dict | None:
        value = self.load().get("mcpServers", {}).get(SERVER_NAME)
        return value if isinstance(value, dict) else None

    def _atomic_bytes(self, content: bytes) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        fd, temporary = tempfile.mkstemp(prefix=".security-check-", suffix=".tmp", dir=self.path.parent)
        try:
            with os.fdopen(fd, "wb") as stream:
                stream.write(content)
                stream.flush()
                os.fsync(stream.fileno())
            os.replace(temporary, self.path)
        finally:
            Path(temporary).unlink(missing_ok=True)

    def _transaction(self, next_value: dict, verify: Callable[[], bool]) -> bool:
        self._check_path()
        original = self.path.read_bytes() if self.path.exists() else None
        serialized = (json.dumps(next_value, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
        if original is not None and json.loads(original.decode("utf-8-sig")) == next_value:
            return False
        if self.backup.exists():
            raise IntegrationConfigError("An earlier configuration backup needs recovery before setup")
        if original is not None:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(self.path, self.backup)
        restored = False
        committed = False
        try:
            self._atomic_bytes(serialized)
            if not verify():
                raise IntegrationConfigError("Runtime MCP verification failed")
            committed = True
        except Exception:
            if original is None:
                self.path.unlink(missing_ok=True)
            else:
                self._atomic_bytes(original)
            restored = True
            raise
        finally:
            if restored or committed:
                self.backup.unlink(missing_ok=True)
        return True

    def install(self, entry: dict, verify: Callable[[], bool]) -> bool:
        created = not self.path.exists()
        value = self.load()
        original = self.path.read_bytes() if not created else None
        # Upgrade Runtime-only files generated by older versions. Mixed user
        # configuration must stay visible to Git and security scans.
        runtime_only = value == {"mcpServers": {SERVER_NAME: entry}}
        value.setdefault("mcpServers", {})[SERVER_NAME] = entry
        changed = self._transaction(value, verify)
        if created or runtime_only:
            try:
                self._local_exclude(add=True)
            except Exception:
                if changed:
                    if original is None:
                        self.path.unlink(missing_ok=True)
                    else:
                        self._atomic_bytes(original)
                raise
        return changed

    def uninstall(self) -> bool:
        value = self.load()
        if SERVER_NAME not in value.get("mcpServers", {}):
            self._local_exclude(add=False)
            return False
        owned = self._local_exclude()
        value["mcpServers"].pop(SERVER_NAME)
        changed = self._transaction(value, lambda: True)
        tracked = GitService(self.workspace)._run("ls-files", "--", self.path.relative_to(self.workspace).as_posix())
        if owned and not tracked and value == {"mcpServers": {}}:
            self.path.unlink()
        self._local_exclude(add=False)
        return changed

    def _local_exclude(self, *, add: bool | None = None) -> bool:
        """Own one exact block; preserve all pre-existing local ignore bytes."""
        git = GitService(self.workspace)
        name = self.path.relative_to(self.workspace).as_posix()
        raw_path = Path(git._run("rev-parse", "--git-path", "info/exclude"))
        exclude = raw_path if raw_path.is_absolute() else self.workspace / raw_path
        if any(item.is_symlink() or item.is_junction() for item in (exclude, exclude.parent)):
            raise IntegrationConfigError("Local ignore symlinks are not supported")
        marker = f"# AI Security Runtime: {name}"
        block = f"\n{marker}\n/{name}\n# End AI Security Runtime: {name}\n".encode("utf-8")
        original = exclude.read_bytes() if exclude.exists() else b""
        owned = block in original
        if add is None:
            return owned
        if add and git._run("ls-files", "--", name):
            return owned
        if add and not owned:
            exclude.parent.mkdir(parents=True, exist_ok=True)
            content = original + block
        elif not add and owned:
            content = original.replace(block, b"", 1)
        else:
            return owned
        fd, temporary = tempfile.mkstemp(prefix=".security-check-exclude-", dir=exclude.parent)
        try:
            with os.fdopen(fd, "wb") as stream:
                stream.write(content)
                stream.flush()
                os.fsync(stream.fileno())
            os.replace(temporary, exclude)
        finally:
            Path(temporary).unlink(missing_ok=True)
        return owned

    def rollback(self) -> bool:
        self._check_path()
        if not self.backup.is_file():
            return False
        self._atomic_bytes(self.backup.read_bytes())
        self.backup.unlink()
        return True
